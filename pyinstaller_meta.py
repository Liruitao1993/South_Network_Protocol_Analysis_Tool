def read_app_version(root: Path) -> str:
    """从 ``main_gui.py`` 读 APP_VERSION（唯一版本源）；读不到回落 ``0.0.0``。"""
    try:
        text = (Path(root) / "main_gui.py").read_text(encoding="utf-8")
    except OSError:
        return "0.0.0"
    match = re.search(r'^APP_VERSION\s*=\s*"([^"]+)"', text, re.M)
    return match.group(1) if match else "0.0.0"


def version_parts(version: str) -> Tuple[int, int, int, int]:
    """``1.23.92`` → ``(1, 23, 92, 0)``（Windows 版本资源固定 4 段）。"""
    parts: List[int] = []
    for piece in str(version).split("."):
        parts.append(int(piece) if piece.isdigit() else 0)
    parts = (parts + [0, 0, 0, 0])[:4]
    return (parts[0], parts[1], parts[2], parts[3])


def version_tuple_text(version: str) -> str:
    """``(1, 23, 92, 0)`` —— VSVersionInfo 的 filevers/prodvers 字面量。"""
    return "(" + ", ".join(str(p) for p in version_parts(version)) + ")"


def version_string(version: str) -> str:
    """``1.23.92.0`` —— 版本资源里的 FileVersion/ProductVersion 字符串。"""
    return ".".join(str(p) for p in version_parts(version))


def onefile_exe_name(version: str, build_ts: str) -> str:
    """单文件形态的产物名：``南网协议解析工具_v1.23.93_20261021183000``。"""
    return f"{PRODUCT_NAME}_v{version}_{build_ts}"


def version_info_text(version: str, original_filename: str) -> str:
    """生成 PyInstaller 的 ``VSVersionInfo`` 文本（``version=`` 参数用）。

    字段刻意补全：``CompanyName``/``FileDescription``/``ProductName``/``LegalCopyright``/
    ``OriginalFilename`` 齐全的 exe，在资源管理器与安全软件眼里才像正规程序；缺字段
    （尤其 OriginalFilename / CompanyName）会拉高启发式风险评分。

    ``original_filename`` 是**产物真实文件名**（含 .exe）：单文件带版本+时间戳，
    文件夹形态就是 ``协议解析工具.exe`` —— 写错会让文件属性与实物对不上。
    """
    tup = version_tuple_text(version)
    vstr = version_string(version)
    return (
        "# UTF-8 (auto-generated by spec, aligned with main_gui.py APP_VERSION)\n"
        "VSVersionInfo(\n"
        "  ffi=FixedFileInfo(\n"
        f"    filevers={tup},\n"
        f"    prodvers={tup},\n"
        "    mask=0x3f,\n"
        "    flags=0x0,\n"
        "    OS=0x40004,\n"
        "    fileType=0x1,\n"
        "    subtype=0x0,\n"
        "    date=(0, 0)\n"
        "  ),\n"
        "  kids=[\n"
        "    StringFileInfo(\n"
        "      [\n"
        "      StringTable(\n"
        "        u'080404B0',\n"
        f"        [StringStruct(u'Comments', u'{COMMENTS}'),\n"
        f"        StringStruct(u'CompanyName', u'{COMPANY_NAME}'),\n"
        f"        StringStruct(u'FileDescription', u'{PRODUCT_NAME}'),\n"
        f"        StringStruct(u'FileVersion', u'{vstr}'),\n"
        f"        StringStruct(u'InternalName', u'{PRODUCT_NAME}'),\n"
        f"        StringStruct(u'LegalCopyright', u'{COPYRIGHT}'),\n"
        f"        StringStruct(u'OriginalFilename', u'{original_filename}'),\n"
        f"        StringStruct(u'ProductName', u'{PRODUCT_NAME}'),\n"
        f"        StringStruct(u'ProductVersion', u'{vstr}')])\n"
        "      ]),\n"
        "    VarFileInfo([VarStruct(u'Translation', [2052, 1200])])\n"
        "  ]\n"
        ")\n"
    )


def manifest_xml(version: str) -> str:
    """应用清单（``manifest=`` 参数用）—— 默认清单 + ``assemblyIdentity``。

    ⚠ **必须给完整清单**：PyInstaller 的 ``create_application_manifest()`` 是整份替换
    而不是合并（只额外保证 requestedExecutionLevel 与 Common-Controls）。早先只传
    ``<assemblyIdentity>``，把 ``supportedOS``(5 条) 与 ``longPathAware`` 一起冲掉了。
    ⚠ 特意**不**声明 dpiAware/dpiAwareness：高 DPI 由 Qt 启动时自己设置，清单再声明一次
    会改变既有缩放行为。
    ⚠ ``requestedExecutionLevel`` 保持 asInvoker —— 本程序不需要提权；要求管理员权限
    只会让安全软件更紧张，也让普通用户装不上。
    """
    vstr = version_string(version)
    return (
        '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\n'
        '<assembly xmlns="urn:schemas-microsoft-com:asm.v1" manifestVersion="1.0">\n'
        '  <assemblyIdentity type="win32" '
        'name="liruitao.SouthNetworkProtocolAnalysisTool" '
        f'version="{vstr}" processorArchitecture="*"/>\n'
        '  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">\n'
        '    <security>\n'
        '      <requestedPrivileges>\n'
        '        <requestedExecutionLevel level="asInvoker" uiAccess="false"/>\n'
        '      </requestedPrivileges>\n'
        '    </security>\n'
        '  </trustInfo>\n'
        '  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">\n'
        '    <application>\n'
        '      <supportedOS Id="{e2011457-1546-43c5-a5fe-008deee3d3f0}"/>\n'
        '      <supportedOS Id="{35138b9a-5d96-4fbd-8e2d-a2440225f93a}"/>\n'
        '      <supportedOS Id="{4a2f28e3-53b9-4441-ba9c-d69d4a4a6e38}"/>\n'
        '      <supportedOS Id="{1f676c76-80e1-4239-95bb-83d0f6d0da78}"/>\n'
        '      <supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}"/>\n'
        '    </application>\n'
        '  </compatibility>\n'
        '  <application xmlns="urn:schemas-microsoft-com:asm.v3">\n'
        '    <windowsSettings>\n'
        '      <longPathAware '
        'xmlns="http://schemas.microsoft.com/SMI/2016/WindowsSettings">true</longPathAware>\n'
        '    </windowsSettings>\n'
        '  </application>\n'
        '  <dependency>\n'
        '    <dependentAssembly>\n'
        '      <assemblyIdentity type="win32" name="Microsoft.Windows.Common-Controls" '
        'version="6.0.0.0" processorArchitecture="*" '
        'publicKeyToken="6595b64144ccf1df" language="*"/>\n'
        '    </dependentAssembly>\n'
        '  </dependency>\n'
        '</assembly>\n'
    )


