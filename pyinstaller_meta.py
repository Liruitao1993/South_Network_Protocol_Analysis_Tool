"""PyInstaller 打包元数据的**单一来源**（两个 spec 共用，避免各写一份而漂移）。

为什么单独成文件：本项目有两种发布形态，两边的版本资源 / 应用清单 / 依赖清单必须一致 ——
  - ``南网协议解析工具.spec``      单文件 exe（便携分发，Release 用的就是它）
  - ``协议解析工具_onedir.spec``   文件夹形态（``dist/协议解析工具/协议解析工具.exe``，
    安装脚本 `南网解析工具.iss` 取的就是这个路径；onedir 无自解压、启动更快、被杀软
    拦的概率更低，见 AGENTS §2.6）

本模块只做**纯文本生成**（不 import PyInstaller），因此可以在任何 Python 下单独跑、
也能被测试逐字节比对。

⚠ 版本号唯一源仍是 ``main_gui.py:APP_VERSION``：本模块只读不写。
"""

